package com.divalhr.core.payroll.domain;

/** The closed evidence codes a statutory profile can cite (MVP-094B, ADR 0034 section 5). */
public enum StatutoryEvidence {
  /** The employment contract. */
  EMPLOYMENT_CONTRACT,
  /** A review of the payroll file. */
  PAYROLL_FILE_REVIEW,
  /** A declaration by the employer. */
  EMPLOYER_DECLARATION,
  /** A professional (legal or tax) review. */
  PROFESSIONAL_REVIEW
}
