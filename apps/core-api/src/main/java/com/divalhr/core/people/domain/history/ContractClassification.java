package com.divalhr.core.people.domain.history;

/**
 * Descriptive contract classification (H13). It has no legal effect and is not a legal
 * classification in any jurisdiction.
 */
public enum ContractClassification {
  /** Open-ended contract. */
  PERMANENT,
  /** Fixed-term contract. */
  FIXED_TERM,
  /** Apprenticeship. */
  APPRENTICESHIP,
  /** Internship. */
  INTERNSHIP,
  /** Daily (casual) work. */
  DAILY
}
