package com.divalhr.core.payroll.internal;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Repository;

/**
 * Read-only storage of the platform-owned statutory rule packs and their official sources
 * (MVP-094B; V45, ADR 0034 section 2). Rule packs are shared reference data: the tables have no
 * tenant column, which is why this repository takes no {@code TenantId} (the single, explicit
 * exception of the tenant-predicate architecture test, which asserts that no statement here names a
 * tenant table). The application has no write path to these tables: a pack enters by migration or
 * by the operational procedure that supplies the professional approval evidence.
 *
 * <p>The verification evidence (reviewer name and organization) is restricted operational evidence:
 * no record here prints it.
 */
@Repository
public class JdbcStatutoryRulePackRepository {

  private static final String PACK_COLUMNS =
      "p.id, p.code, p.version, p.country, p.currency, p.status, p.effective_from,"
          + " p.effective_to, p.method_version, p.rules_digest, p.reviewer_name,"
          + " p.reviewer_organization, p.reviewed_on, p.attested, p.verified_at,"
          + " (SELECT count(*) FROM payroll.statutory_rule_pack_source s WHERE s.pack_id = p.id)"
          + " AS source_count";

  private final JdbcClient jdbc;

  /**
   * Creates the repository.
   *
   * @param jdbc JDBC client
   */
  public JdbcStatutoryRulePackRepository(JdbcClient jdbc) {
    this.jdbc = jdbc;
  }

  /**
   * A stored rule pack without its rules document.
   *
   * @param id pack
   * @param code pack code
   * @param version pack version
   * @param country {@code CD}
   * @param currency {@code CDF}
   * @param status {@code DRAFT}, {@code VERIFIED} or {@code RETIRED}
   * @param effectiveFrom first day of the interval
   * @param effectiveTo last day of the interval, or {@code null} when open
   * @param methodVersion calculation-method version
   * @param rulesDigest SHA-256 of the rules, generated by the database
   * @param reviewerName reviewer, or {@code null} while DRAFT (restricted)
   * @param reviewerOrganization reviewer organization, or {@code null} while DRAFT (restricted)
   * @param reviewedOn review date, or {@code null} while DRAFT
   * @param attested whether the professional review was attested
   * @param verifiedAt verification instant, or {@code null} while DRAFT
   * @param sourceCount number of official sources
   */
  public record PackRow(
      UUID id,
      String code,
      int version,
      String country,
      String currency,
      String status,
      LocalDate effectiveFrom,
      LocalDate effectiveTo,
      int methodVersion,
      String rulesDigest,
      String reviewerName,
      String reviewerOrganization,
      LocalDate reviewedOn,
      boolean attested,
      Instant verifiedAt,
      int sourceCount) {

    @Override
    public String toString() {
      return "StatutoryRulePack[" + id + "]";
    }
  }

  /**
   * One official source of a pack.
   *
   * @param key closed source key
   * @param title title
   * @param url https URL on an allow-listed official host
   * @param sha256 SHA-256 of the retrieved document, or {@code null} while DRAFT
   * @param retrievedOn retrieval date
   */
  public record SourceRow(
      String key, String title, String url, String sha256, LocalDate retrievedOn) {}

  /**
   * Where a pack page continues after.
   *
   * @param effectiveFrom the last row's first day
   * @param code the last row's code
   * @param version the last row's version
   */
  public record PackPosition(LocalDate effectiveFrom, String code, int version) {}

  /**
   * One pack, with its rules document as stored (parsed and validated by the caller).
   *
   * @param row the pack
   * @param rules the {@code rules} document as text
   */
  public record PackWithRules(PackRow row, String rules) {

    @Override
    public String toString() {
      return "StatutoryRulePackWithRules[" + row.id() + "]";
    }
  }

  /**
   * One pack without its rules.
   *
   * @param packId pack
   * @return the pack, if it exists
   */
  public Optional<PackRow> pack(UUID packId) {
    return jdbc.sql(
            "SELECT " + PACK_COLUMNS + " FROM payroll.statutory_rule_pack p WHERE p.id = :id")
        .param("id", packId)
        .query(JdbcStatutoryRulePackRepository::pack)
        .optional();
  }

  /**
   * One pack with its rules document.
   *
   * @param packId pack
   * @return the pack with its rules, if it exists
   */
  public Optional<PackWithRules> packWithRules(UUID packId) {
    return jdbc.sql(
            "SELECT "
                + PACK_COLUMNS
                + ", p.rules::text AS rules_text FROM payroll.statutory_rule_pack p"
                + " WHERE p.id = :id")
        .param("id", packId)
        .query((rs, row) -> new PackWithRules(pack(rs, row), rs.getString("rules_text")))
        .optional();
  }

  /**
   * A page of packs: newest effective date first, then code, then version descending.
   *
   * @param status status filter, or {@code null} for every status
   * @param after the last row of the previous page, or {@code null} for the first page
   * @param limit rows to read
   * @return the packs
   */
  public List<PackRow> packPage(String status, PackPosition after, int limit) {
    if (after == null) {
      return jdbc.sql(
              "SELECT "
                  + PACK_COLUMNS
                  + " FROM payroll.statutory_rule_pack p"
                  + " WHERE (CAST(:status AS text) IS NULL OR p.status = CAST(:status AS text))"
                  + " ORDER BY p.effective_from DESC, p.code, p.version DESC LIMIT :limit")
          .param("status", status)
          .param("limit", limit)
          .query(JdbcStatutoryRulePackRepository::pack)
          .list();
    }
    return jdbc.sql(
            "SELECT "
                + PACK_COLUMNS
                + " FROM payroll.statutory_rule_pack p"
                + " WHERE (CAST(:status AS text) IS NULL OR p.status = CAST(:status AS text))"
                + " AND (p.effective_from < :from"
                + " OR (p.effective_from = :from AND p.code > :code)"
                + " OR (p.effective_from = :from AND p.code = :code AND p.version < :version))"
                + " ORDER BY p.effective_from DESC, p.code, p.version DESC LIMIT :limit")
        .param("status", status)
        .param("from", after.effectiveFrom())
        .param("code", after.code())
        .param("version", after.version())
        .param("limit", limit)
        .query(JdbcStatutoryRulePackRepository::pack)
        .list();
  }

  /**
   * The official sources of a pack, in order.
   *
   * @param packId pack
   * @return the sources
   */
  public List<SourceRow> sources(UUID packId) {
    return jdbc.sql(
            "SELECT source_key, title, url, sha256, retrieved_on"
                + " FROM payroll.statutory_rule_pack_source WHERE pack_id = :pack ORDER BY seq")
        .param("pack", packId)
        .query(
            (rs, row) ->
                new SourceRow(
                    rs.getString("source_key"),
                    rs.getString("title"),
                    rs.getString("url"),
                    rs.getString("sha256"),
                    rs.getObject("retrieved_on", LocalDate.class)))
        .list();
  }

  private static PackRow pack(ResultSet rs, int row) throws SQLException {
    Timestamp verified = rs.getTimestamp("verified_at");
    String digest = rs.getString("rules_digest");
    return new PackRow(
        rs.getObject("id", UUID.class),
        rs.getString("code"),
        rs.getInt("version"),
        rs.getString("country"),
        rs.getString("currency"),
        rs.getString("status"),
        rs.getObject("effective_from", LocalDate.class),
        rs.getObject("effective_to", LocalDate.class),
        Integer.parseInt(rs.getString("method_version")),
        digest == null ? null : digest.trim(),
        rs.getString("reviewer_name"),
        rs.getString("reviewer_organization"),
        rs.getObject("reviewed_on", LocalDate.class),
        rs.getBoolean("attested"),
        verified == null ? null : verified.toInstant(),
        rs.getInt("source_count"));
  }
}
